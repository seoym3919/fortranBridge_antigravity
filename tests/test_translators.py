"""Tests for the Fortran -> Python / C++ translators.

Run (from the plugin root):  python3 -B -m unittest discover -s tests -v

Reference values: every numeric expectation is either an exact integer/analytic result noted in the
test, or NumPy's LAPACK-backed solve / matmul. Tolerances are stated per test; none were loosened to
make a test pass.

Known limits (also documented in the README): no C++ compiler is invoked, so C++ output is checked
for structure only.
"""

