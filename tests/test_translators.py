_MODULE_COUNTER = [0]


def load(src):
    """Translate Fortran source and exec the resulting Python; returns its namespace."""
    code = translate_fortran_to_python(src)
    _MODULE_COUNTER[0] += 1
    mod = types.ModuleType(f"translated_{_MODULE_COUNTER[0]}")
    sys.modules[mod.__name__] = mod                  # dataclasses look the defining module up here
    exec(compile(code, "<translated>", "exec"), mod.__dict__)  # noqa: S102 - generated by the code under test
    return mod.__dict__


TRIDIAG = """\
subroutine tridiag(n, a, b, c, d, x)
  implicit none
  integer, intent(in) :: n
  real(8), intent(in) :: a(n), b(n), c(n), d(n)
  real(8), intent(out) :: x(n)
  real(8) :: cp(n), dp(n), m
  integer :: i
  cp(1) = c(1)/b(1)
  dp(1) = d(1)/b(1)
  do i = 2, n
    m = b(i) - a(i)*cp(i-1)
    cp(i) = c(i)/m
    dp(i) = (d(i) - a(i)*dp(i-1))/m
  end do
  x(n) = dp(n)
  do i = n-1, 1, -1
    x(i) = dp(i) - cp(i)*x(i+1)
  end do
end subroutine tridiag
"""

TRIDIAG_F77 = """\
      SUBROUTINE TRIDG(N, A, B, C, D, X)
      INTEGER N
      DOUBLE PRECISION A(N), B(N), C(N), D(N), X(N), CP(N), DP(N), M
      CP(1) = C(1)/B(1)
      DP(1) = D(1)/B(1)
      DO 10 I = 2, N
         M = B(I) - A(I)*CP(I-1)
         CP(I) = C(I)/M
         DP(I) = (D(I) - A(I)*DP(I-1))/M
 10   CONTINUE
      X(N) = DP(N)
      DO 20 I = N-1, 1, -1
         X(I) = DP(I) - CP(I)*X(I+1)
 20   CONTINUE
      RETURN
      END
"""


class ExpressionParserTests(unittest.TestCase):
    def test_precedence_and_associativity(self):
        e = parse_expression("a + b * c ** d ** e")
        self.assertEqual(e.op, "+")
        self.assertEqual(e.right.op, "*")
        pow1 = e.right.right
        self.assertEqual(pow1.op, "**")
        self.assertEqual(pow1.right.op, "**")            # ** is right associative

    def test_unary_minus_binds_looser_than_power(self):
        e = parse_expression("-a**2")
        self.assertIsInstance(e, Unary)
        self.assertEqual(e.operand.op, "**")

    def test_double_precision_literals(self):
        self.assertEqual(parse_expression("1.0D-12").text, "1.0e-12")
        self.assertEqual(parse_expression("0.5D0").text, "0.5")
        self.assertTrue(parse_expression("3").is_int)
        self.assertFalse(parse_expression("3.").is_int)

    def test_nested_array_refs_and_relational(self):
        e = parse_expression("a(idx(i)+1) .LT. b(2,3) .AND. .NOT. flag")
        self.assertEqual(e.op, "and")
        self.assertEqual(e.left.op, "<")
        self.assertIsInstance(e.left.left, Ref)

    def test_static_types(self):
        stmts, units = lex_and_split("integer function f(n)\ninteger n\nf = n/2\nend\n")
        u = units[0]
        self.assertEqual(infer_type(parse_expression("n/2"), u), "integer")
        self.assertEqual(infer_type(parse_expression("n/2.0"), u), "real")
        self.assertEqual(infer_type(parse_expression("n .GT. 1"), u), "logical")


class LexerTests(unittest.TestCase):
    CASES = {
        "real(8), intent(in) :: a(n), b(n)": ("TYPE_DECL", {"type": "REAL*8", "intent": "in"}),
        "real(8) :: cp(n), dp(n), m": ("TYPE_DECL", {"type": "REAL*8"}),
        "DOUBLE PRECISION X, Y": ("TYPE_DECL", {"type": "DOUBLE PRECISION"}),
        "INTEGER*4 N": ("TYPE_DECL", {"type": "INTEGER*4"}),
        "real(8), parameter :: pi = 3.14d0": ("TYPE_DECL", {"is_parameter": True}),
        "real(8) function f(x)": ("FUNCTION", {"name": "f", "result_type": "REAL*8"}),
        "end subroutine tridiag": ("END", {}),
        "IF (a(i) .LT. 0) x = 1": ("IF_STMT", {"condition": "a(i) .LT. 0", "statement": "x = 1"}),
        "IF (x .GT. (y+1)) THEN": ("IF_THEN", {"condition": "x .GT. (y+1)"}),
        "IF (x) 10, 20, 30": ("ARITHMETIC_IF", {"label_pos": "30"}),
        "DO WHILE (x .GE. 0)": ("DO_WHILE", {"condition": "x .GE. 0"}),
        "EXIT": ("EXIT", {}),
        "REALVAL = 1.0": ("ASSIGNMENT", {"lhs": "REALVAL"}),
    }

    def test_classification(self):
        for text, (kind, expect) in self.CASES.items():
            got_kind, details = classify_statement(text)
            self.assertEqual(got_kind, kind, text)
            for k, v in expect.items():
                self.assertEqual(details.get(k), v, f"{text}: {k}")


class PythonNumericsTests(unittest.TestCase):
    """Execute the translated Python and compare with an independent reference."""

    def _system(self, n, seed=0):
        rng = np.random.default_rng(seed)               # fixed seed: reproducible
        a, b, c, d = rng.random(n), 4 + rng.random(n), rng.random(n), rng.random(n)
        a[0] = 0.0
        c[-1] = 0.0
        full = np.diag(b) + np.diag(a[1:], -1) + np.diag(c[:-1], 1)
        return a, b, c, d, np.linalg.solve(full, d)

    def test_tridiagonal_free_form_matches_lapack(self):
        ns = load(TRIDIAG)
        a, b, c, d, ref = self._system(8)
        x = np.zeros(8)
        ns["tridiag"](8, a, b, c, d, x)
        np.testing.assert_allclose(x, ref, rtol=1e-12, atol=1e-14)   # observed ~1e-17

    def test_tridiagonal_fixed_form_matches_lapack(self):
        ns = load(TRIDIAG_F77)
        a, b, c, d, ref = self._system(11, seed=3)
        x = np.zeros(11)
        ns["tridg"](11, a, b, c, d, x)
        np.testing.assert_allclose(x, ref, rtol=1e-12, atol=1e-14)

    def test_integer_division_truncates_toward_zero(self):
        ns = load("integer function half(n)\ninteger n\nhalf = n/2\nend function half\n")
        self.assertEqual(ns["half"](7), 3)
        self.assertEqual(ns["half"](-7), -3)             # Fortran: -3; Python // would give -4

    def test_real_division_is_not_truncated(self):
        ns = load("real(8) function h(n)\ninteger n\nh = n/2.0d0\nend function h\n")
        self.assertEqual(ns["h"](7), 3.5)

    def test_loop_variable_value_is_fortran_value(self):
        src = "integer function tri(n)\ninteger n, i, s\ns = 0\ndo i = 1, n\n  s = s + i\nend do\ntri = s\nend function tri\n"
        self.assertEqual(load(src)["tri"](100), 5050)    # n(n+1)/2

    def test_loop_steps_and_zero_trip(self):
        src = ("integer function cnt(lo, hi, st)\ninteger lo, hi, st, i, k\nk = 0\ndo i = lo, hi, st\n  k = k + 1\n"
               "end do\ncnt = k\nend function cnt\n")
        cnt = load(src)["cnt"]
        self.assertEqual(cnt(1, 10, 2), 5)               # 1,3,5,7,9
        self.assertEqual(cnt(10, 1, -3), 4)              # 10,7,4,1
        self.assertEqual(cnt(5, 1, 1), 0)                # zero-trip loop
        self.assertEqual(cnt(1, 0, -1), 2)               # 1,0

    def test_scalar_outputs_are_returned(self):
        src = ("subroutine stats(n, x, mean, var)\ninteger, intent(in) :: n\nreal(8), intent(in) :: x(n)\n"
               "real(8), intent(out) :: mean, var\ninteger :: i\nmean = 0.0d0\ndo i = 1, n\n  mean = mean + x(i)\n"
               "end do\nmean = mean/n\nvar = 0.0d0\ndo i = 1, n\n  var = var + (x(i)-mean)**2\nend do\nvar = var/n\n"
               "end subroutine stats\n")
        x = np.random.default_rng(1).random(50)
        mean, var = load(src)["stats"](50, x)
        self.assertAlmostEqual(mean, x.mean(), places=14)
        self.assertAlmostEqual(var, x.var(), places=14)          # population variance

    def test_call_assigns_scalar_results_back(self):
        src = ("subroutine addone(k)\ninteger k\nk = k + 1\nend subroutine addone\n"
               "integer function bump(n)\ninteger n, k\nk = n\ncall addone(k)\ncall addone(k)\nbump = k\n"
               "end function bump\n"
               "subroutine twice(k)\ninteger k\ncall addone(k)\ncall addone(k)\nend subroutine twice\n")
        ns = load(src)
        self.assertEqual(ns["bump"](5), 7)
        self.assertEqual(ns["twice"](10), 12)            # modification propagates through a dummy

    def test_two_dimensional_arrays_match_numpy(self):
        src = ("subroutine matvec(n, m, a, x, y)\ninteger n, m, i, j\nreal(8) a(n, m), x(m), y(n)\n"
               "do i = 1, n\n  y(i) = 0.0d0\n  do j = 1, m\n    y(i) = y(i) + a(i, j)*x(j)\n  end do\nend do\n"
               "end subroutine matvec\n")
        rng = np.random.default_rng(2)
        a, x = rng.random((4, 3)), rng.random(3)
        y = np.zeros(4)
        load(src)["matvec"](4, 3, a, x, y)
        np.testing.assert_allclose(y, a @ x, rtol=1e-13)

    def test_local_2d_array_and_lower_bounds(self):
        src = ("real(8) function g(n)\ninteger n, i\nreal(8) w(0:n), t(2, 3)\nt(2, 3) = 7.0d0\n"
               "do i = 0, n\n  w(i) = i\nend do\ng = w(n) + w(0) + t(2, 3)\nend function g\n")
        self.assertEqual(load(src)["g"](5), 5.0 + 0.0 + 7.0)

    def test_while_exit_cycle(self):
        src = ("integer function f(n)\ninteger n, i, s\ns = 0\ni = 0\ndo while (i .LT. n)\n  i = i + 1\n"
               "  if (mod(i, 2) .EQ. 0) cycle\n  if (i .GT. 7) exit\n  s = s + i\nend do\nf = s\nend function f\n")
        self.assertEqual(load(src)["f"](100), 1 + 3 + 5 + 7)

    def test_if_elseif_else(self):
        src = ("integer function sgn(x)\nreal(8) x\nif (x .GT. 0.0d0 .AND. x .LT. 1.0d9) then\n  sgn = 1\n"
               "else if (x .LT. 0.0d0) then\n  sgn = -1\nelse\n  sgn = 0\nend if\nend function sgn\n")
        sgn = load(src)["sgn"]
        self.assertEqual([sgn(2.0), sgn(-3.0), sgn(0.0), sgn(2e9)], [1, -1, 0, 0])

    def test_intrinsics(self):
        src = ("real(8) function f(a, b)\nreal(8) a, b\nf = max(a, b) + min(a, b) + sign(3.0d0, -a) + dsqrt(abs(b))\n"
               "end function f\ninteger function g(x)\nreal(8) x\ng = nint(x)\nend function g\n"
               "integer function h(i, j)\ninteger i, j\nh = mod(i, j)\nend function h\n")
        ns = load(src)
        self.assertAlmostEqual(ns["f"](2.0, 9.0), 9.0 + 2.0 - 3.0 + 3.0, places=14)
        self.assertEqual([ns["g"](2.5), ns["g"](-2.5), ns["g"](0.4)], [3, -3, 0])   # half away from zero
        self.assertEqual([ns["h"](7, 3), ns["h"](-7, 3)], [1, -1])                   # sign follows dividend

    def test_string_literals_keep_their_case(self):
        ns = load("subroutine hello()\nprint *, 'Hello, WORLD'\nend subroutine hello\n")
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            ns["hello"]()
        self.assertEqual(buf.getvalue().strip(), "Hello, WORLD")

    def test_python_keywords_and_builtins_are_renamed(self):
        src = "real(8) function f(lambda, max)\nreal(8) lambda, max\nf = lambda + max\nend function f\n"
        self.assertEqual(load(src)["f"](1.5, 2.0), 3.5)

    def test_common_block_state_is_shared(self):
        src = ("subroutine setit(v)\nreal(8) v\nreal(8) gx\ncommon /state/ gx\ngx = v\nend subroutine setit\n"
               "real(8) function getit()\nreal(8) gx\ncommon /state/ gx\ngetit = 2.0d0*gx\nend function getit\n"
               "real(8) function both(v)\nreal(8) v\ncall setit(v)\nboth = getit()\nend function both\n")
        ns = load(src)
        blk = ns["StateBlock"]()
        ns["setit"](4.0, blk)
        self.assertEqual(blk.gx, 4.0)
        self.assertEqual(ns["getit"](blk), 8.0)
        self.assertEqual(ns["both"](5.0, blk), 10.0)     # COMMON propagates to the caller's signature

    def test_goto_translates_but_fails_loudly(self):
        src = "subroutine s(x)\nreal(8) x\nif (x .LT. 0.0d0) goto 99\nx = 1.0d0\n99 continue\nend subroutine s\n"
        ns = load(src)                                   # translation itself must succeed
        with self.assertRaises(NotImplementedError):
            ns["s"](-1.0)

    def test_unsupported_statements_are_never_dropped(self):
        for stmt in ("data k /5/", "equivalence (a, b)"):
            code = translate_fortran_to_python(f"subroutine s()\ninteger k\nreal a, b\n{stmt}\nend subroutine s\n")
            self.assertIn("NotImplementedError", code, stmt)

    def test_generated_code_always_parses(self):
        for src in (TRIDIAG, TRIDIAG_F77, (ROOT / "examples" / "legacy_orbit.f").read_text()):
            compile(translate_fortran_to_python(src), "<translated>", "exec")

    def test_orbit_example_matches_independent_leapfrog(self):
        """legacy_orbit.f: semi-implicit Euler (kick then drift) for a softened point mass."""
        ns = load((ROOT / "examples" / "legacy_orbit.f").read_text())
        gm, dt, steps, soft = 1.0, 0.01, 200, 1e-6
        r0, v0 = np.array([1.0, 0.0, 0.0]), np.array([0.0, 1.0, 0.0])
        rf, vf = np.zeros(3), np.zeros(3)
        blk = ns["OrbitStateBlock"]()
        ns["propagate_orbit"](r0, v0, dt, gm, rf, vf, steps, blk)
        r, v = r0.copy(), v0.copy()
        for _ in range(steps):
            rm = np.sqrt(r @ r + soft**2)            # R_MAG of this step, evaluated before the drift
            v = v + dt * (-gm / rm**3) * r
            r = r + dt * v
        np.testing.assert_allclose(rf, r, rtol=1e-12)
        np.testing.assert_allclose(vf, v, rtol=1e-12)
        # the Fortran source reuses the *last step's* R_MAG (not the final position) in the energy
        self.assertAlmostEqual(blk.energy, 0.5 * (v @ v) - gm / rm, delta=1e-10)


class CppStructureTests(unittest.TestCase):
    def test_tridiag_structure(self):
        cpp = translate_fortran_to_cpp(TRIDIAG)
        self.assertIn("void tridiag(int n, const std::vector<double>& a,", cpp)
        self.assertIn("std::vector<double>& x)", cpp)
        self.assertIn("for (i = 2; i <= n; ++i) {", cpp)
        self.assertIn("for (i = n - 1; i >= 1; --i) {", cpp)
        self.assertIn("m = b[i - 1] - a[i - 1] * cp[i - 2];", cpp)
        self.assertIn("std::vector<double> cp(n);", cpp)

    def test_braces_and_parens_balance(self):
        for src in (TRIDIAG, TRIDIAG_F77, (ROOT / "examples" / "legacy_orbit.f").read_text()):
            cpp = translate_fortran_to_cpp(src)
            body = re.sub(r'"(?:\\.|[^"\\])*"', '""', cpp)
            for o, c in ("{}", "()", "[]"):
                self.assertEqual(body.count(o), body.count(c), (o, c))

    def test_goto_and_labels_are_kept(self):
        cpp = translate_fortran_to_cpp((ROOT / "examples" / "legacy_orbit.f").read_text())
        self.assertIn("goto label_999;", cpp)
        self.assertIn("label_999: ;", cpp)
        self.assertIn("struct OrbitStateBlock", cpp)
        self.assertIn("OrbitStateBlock& orbit_state_common", cpp)

    def test_locals_are_declared_before_any_label(self):
        cpp = translate_fortran_to_cpp((ROOT / "examples" / "legacy_orbit.f").read_text())
        first_label = cpp.index("label_999: ;")
        for decl in ("int step{};", "double r_mag{};", "std::vector<double> r_curr(3);"):
            self.assertLess(cpp.index(decl), first_label, decl)   # goto must not cross an initialisation

    def test_two_dimensional_local_array(self):
        cpp = translate_fortran_to_cpp("real(8) function g(n, m)\ninteger n, m\nreal(8) a(n, m)\na(1, 2) = 1.0d0\n"
                                       "g = a(1, 2)\nend function g\n")
        self.assertIn("std::vector<std::vector<double>> a(n, std::vector<double>(m));", cpp)
        self.assertIn("a[0][1] = 1.0;", cpp)

    def test_scalar_outputs_are_references(self):
        cpp = translate_fortran_to_cpp("subroutine addone(k)\ninteger k\nk = k + 1\nend subroutine addone\n")
        self.assertIn("void addone(int& k)", cpp)

    def test_by_reference_actual_that_is_not_an_lvalue_uses_a_temporary(self):
        cpp = translate_fortran_to_cpp("subroutine addone(k)\ninteger k\nk = k + 1\nend subroutine addone\n"
                                       "subroutine t()\ncall addone(5)\nend subroutine t\n")
        self.assertIn("int tmp1_ = 5;", cpp)
        self.assertIn("addone(tmp1_);", cpp)

    def test_integer_power_and_division(self):
        cpp = translate_fortran_to_cpp("integer function f(n)\ninteger n\nf = n/2 + n**2 + 2**n\nend function f\n")
        self.assertIn("n / 2", cpp)
        self.assertIn("(n * n)", cpp)
        self.assertIn("static_cast<int>(std::pow(2, n))", cpp)

    def test_unsupported_becomes_throw(self):
        cpp = translate_fortran_to_cpp("subroutine s()\ninteger k\ndata k /5/\nend subroutine s\n")
        self.assertIn('throw std::logic_error("fortranBridge:', cpp)

    def test_reserved_words_are_renamed(self):
        cpp = translate_fortran_to_cpp("real(8) function f(new, class)\nreal(8) new, class\nf = new + class\nend function f\n")
        self.assertIn("double new_", cpp)
        self.assertIn("double class_", cpp)


class CliTests(unittest.TestCase):
    CLI = str(SCRIPTS / "fortran_bridge_cli.py")

    def run_cli(self, *args, cwd=None):
        return subprocess.run([sys.executable, "-B", self.CLI, *args], capture_output=True, text=True, cwd=cwd)

    def test_self_test_passes(self):
        res = self.run_cli("--self-test")
        self.assertEqual(res.returncode, 0, res.stderr[-500:])

    def test_single_file_python_and_cpp(self):
        with tempfile.TemporaryDirectory() as d:
            src = Path(d) / "tri.f90"
            src.write_text(TRIDIAG)
            res = self.run_cli(str(src), "--target", "both", cwd=d)
            self.assertEqual(res.returncode, 0, res.stderr)
            compile((Path(d) / "tri.py").read_text(), "tri.py", "exec")
            self.assertIn("void tridiag", (Path(d) / "tri.cpp").read_text())

    def test_untranslated_constructs_are_reported_on_stderr(self):
        with tempfile.TemporaryDirectory() as d:
            res = self.run_cli(str(ROOT / "examples" / "legacy_orbit.f"), "--target", "python", "--out", str(Path(d) / "o.py"))
            self.assertEqual(res.returncode, 0)
            self.assertIn("not translated", res.stderr)

    def test_directory_mode(self):
        with tempfile.TemporaryDirectory() as d:
            proj = Path(d) / "proj"
            proj.mkdir()
            (proj / "tri.f90").write_text(TRIDIAG)
            out = Path(d) / "out"
            res = self.run_cli(str(proj), "--target", "python", "--out-dir", str(out), "--report", str(Path(d) / "r.md"))
            self.assertEqual(res.returncode, 0, res.stderr)
            self.assertTrue((out / "tri.py").exists())
            self.assertTrue((out / "__init__.py").exists())
            self.assertTrue((Path(d) / "r.md").exists())

    def test_documented_flags_exist(self):
        """Every --flag shown next to fortran_bridge_cli.py in rules/skills/agents/README is a real option."""
        helptext = self.run_cli("--help").stdout
        real = set(re.findall(r"--[a-z][a-z0-9-]*", helptext))
        docs = list((ROOT / "rules").glob("*.md")) + [ROOT / "README.md"]
        docs += list((ROOT / "skills").glob("*/SKILL.md")) + list((ROOT / "agents").glob("*.md"))
        for doc in docs:
            for line in doc.read_text().splitlines():
                if "fortran_bridge_cli.py" in line:
                    for flag in re.findall(r"(?<![\w-])--[a-z][a-z0-9-]*", line):
                        self.assertIn(flag, real, f"{doc.name}: {line.strip()}")
                    self.assertNotRegex(line, r"\s-o\s", f"{doc.name}: no '-o' option exists")


class AllScriptsDocFlagsTests(unittest.TestCase):
    """Every --flag written after `scripts/<name>.py` in rules/skills/agents/README must exist in that script."""

    def test_documented_flags_exist_for_every_script(self):
        docs = list((ROOT / "rules").glob("*.md")) + [ROOT / "README.md"]
        docs += list((ROOT / "skills").glob("*/SKILL.md")) + list((ROOT / "agents").glob("*.md"))
        help_cache = {}
        for doc in docs:
            for line in doc.read_text().splitlines():
                for script in set(re.findall(r"scripts/(\w+)\.py", line)):
                    path = SCRIPTS / f"{script}.py"
                    if not path.exists():
                        self.fail(f"{doc.name} references missing script {script}.py")
                    if "argparse" not in path.read_text():
                        continue
                    if script not in help_cache:
                        res = subprocess.run([sys.executable, "-B", str(path), "--help"],
                                             capture_output=True, text=True, timeout=60)
                        help_cache[script] = set(re.findall(r"--[a-z][a-z0-9-]*", res.stdout))
                    for flag in re.findall(r"(?<![\w-])--[a-z][a-z0-9-]*", line.split(f"{script}.py", 1)[-1]):
                        self.assertIn(flag, help_cache[script], f"{doc.name}: {script}.py {flag}")


class PortabilityTests(unittest.TestCase):
    """The scripts must keep working on Python 3.10 (the oldest CI version)."""

    def test_no_backslash_inside_fstring_expressions(self):
        # A backslash inside the {...} of an f-string is a SyntaxError before Python 3.12.
        import ast
        for path in sorted(SCRIPTS.glob("*.py")):
            src = path.read_text()
            for node in ast.walk(ast.parse(src)):
                if isinstance(node, ast.FormattedValue):
                    segment = ast.get_source_segment(src, node.value) or ""
                    self.assertNotIn("\\", segment, f"{path.name}:{node.lineno}: {segment!r}")


